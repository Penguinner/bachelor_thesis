use crate::{AFFILIATIONS_FILE, ALIAS_FILE, AUTHOR_FILE, AUTHOR_WEBSITES_FILE, EDITOR_FILE, PUBLICATION_AUTHORS_FILE, PUBLICATION_EDITOR_FILE, PUBLICATION_FILE, PUBLISHER_FILE, REFERENCE_FILE, RESOURCES_FILE, VENUE_FILE};
use duckdb::{params, Connection, Row, Statement};
use std::error::Error;
use std::fs;
use std::fs::{File, OpenOptions};
use std::io::{Read, Write};

use crate::Dataset;

/// Connection for a DuckDB Database
pub struct DuckDBConnection {
    connection: Connection,
    dataset: Dataset,
}

impl DuckDBConnection {

    /// Create a new [`DuckDBConnection`] from a [`Dataset`]
    pub fn new(dataset: Dataset) -> Result<DuckDBConnection,  Box<dyn Error >> {
        // Create DuckDB database at db.duckdb
        let mut conn = DuckDBConnection { connection: Connection::open("db.duckdb").unwrap(), dataset: dataset.clone() };
        // Additional initialization depending on dataset
        match dataset {
            Dataset::Dblp => {
                conn.create_tables_dblp();
                conn.insert_dblp_data();
            },
            Dataset::OsmPlanet => {
                conn.load_spatial_module();
                conn.load_osm_planet_data();
            }
        }

        // Activate Profiling for query timing
        conn.activate_profiling();
        Ok(conn)
    }

    /// Flushes the statement cache to ensure cold queries
    pub fn cooldown(&mut self) -> () {
        self.connection.flush_prepared_statement_cache();
    }

    /// Activates DuckDBs profiling to time queries
    fn activate_profiling(&mut self) {
        self.connection.execute("PRAGMA enable_profiling = 'no_output'", []).unwrap();
        self.connection.execute("PRAGMA profiling_mode = 'standard'", []).unwrap();
    }

    /// Installs and loads the DuckDB spatial module to work with spatial data
    fn load_spatial_module(&mut self) {
        self.connection.execute("INSTALL spatial;", []).unwrap();
        self.connection.execute("LOAD spatial;", []).unwrap();
    }

    /// Use ST_ReadOSM to read osm planet data to duckdb.
    fn load_osm_planet_data(&mut self) {
        let file_path = format!("/extern/data/planet-latest.osm.pbf");
        let query = format!("CREATE TABLE osm AS SELECT * FROM ST_ReadOSM('{file_path}');");
        self.connection.execute(&query, []).unwrap();
    }

    /// Creates all tables necessary for the dblp dataset.
    pub fn create_tables_dblp(&mut self) {
        let mut file = File::open("create_tables_dblp.sql").unwrap();
        let mut query = String::new();
        file.read_to_string(&mut query).unwrap();
        query = format!("BEGIN;\n {}\n COMMIT;", query);
        self.connection.execute_batch(&query).unwrap();
        println!("Created Tables DBLP");
    }

    /// Reads the different csv files generated by the parser and reads them into the database via CSV Reader
    pub fn insert_dblp_data(&mut self) {
        let query = format!(
            "BEGIN;\n\
             COPY Venues FROM '{0}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Publishers FROM '{1}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Editors FROM '{2}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Authors FROM '{3}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Publications FROM '{4}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Resources FROM '{5}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY PublicationEditors FROM '{6}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Reference FROM '{7}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY PublicationAuthors FROM '{8}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY AuthorWebsites FROM '{9}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Affiliations FROM '{10}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             COPY Alias FROM '{11}' (FORMAT CSV, DELIMITER E'\\t', HEADER true);\n\
             END;",
            VENUE_FILE,
            PUBLISHER_FILE,
            EDITOR_FILE,
            AUTHOR_FILE,
            PUBLICATION_FILE,
            RESOURCES_FILE,
            PUBLICATION_EDITOR_FILE,
            REFERENCE_FILE,
            PUBLICATION_AUTHORS_FILE,
            AUTHOR_WEBSITES_FILE,
            AFFILIATIONS_FILE,
            ALIAS_FILE
        );
        self.connection.execute_batch(&query).unwrap();
        println!("Inserted DBLP data into DuckDB");
    }

    /// Runs a test query on duckdb database
    pub fn run_test_query(&self, query: &str) -> Result<u128, Box<dyn Error>> {
        // Execute the query
        let mut stmt: Statement<'_> = self.connection.prepare(query)?;
        let response: Result<Row<'_>, Box<dyn Error>> = stmt.query(params![]);
        // Get timing info from profiling
        let profiling = self.connection.get_profiling_info().expect("profiling should be enabled");
        let duration_secs = profiling.metrics["LATENCY"].parse::<f64>().unwrap();
        let duration = (duration_secs * 1000.0).round() as u128;
        // Write query result info to log
        let logmsg: String;
        let result: Result<u128, Box<dyn Error>> = match response {
            Ok(_) => {
                logmsg = format!("Query: {0}\nDuration: {1}\nResult Size: Columns {2} Rows {3}", query, duration, stmt.column_count(), stmt.row_count());
                Ok(duration)
            },
            Err(e) => {
                logmsg = format!("Query: {0} failed\n {e}", query);
                Err(e)
            }
        };
        let mut file = OpenOptions::new()
            .write(true)
            .create(true)
            .append(true)
            .open(format!("/extern/data/duckdb.{}.log", self.dataset.name()))
            .unwrap();
        let _ = file.write(logmsg.as_bytes());

        result
    }
    
    /// Close Connection and delete the database file
    pub fn close(self) -> Result<(), Box<dyn Error>> {
        fs::remove_file("db.duckdb").unwrap();
        self.connection.close().expect("connection close failed");
        Ok(())
    }
}